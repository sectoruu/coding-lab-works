A = [2, 5, 1, 2, 10]
B = []
for i in range(len(A)): #цикл в довжину списка
    i += 1 #збільшити лічильник на 1
    B.append(sum(A[0:i])) #добавити до списку B суму зрізу
print(B)

# Другий спосіб
B1 = []
acc = 0
for x in A:
    acc += x #збільшити акумулятор на число
    B1.append(acc) #добавити елемент в список
print(B1)
